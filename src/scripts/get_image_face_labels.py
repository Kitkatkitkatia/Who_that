import argparse
import csv
import json
import sys
from pathlib import Path

import cv2
import numpy as np

ROOT_DIR = Path(__file__).resolve().parents[2]
if str(ROOT_DIR) not in sys.path:
    sys.path.insert(0, str(ROOT_DIR))

IMAGE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".webp", ".bmp"}


def load_reference_embeddings(npz_path: Path) -> tuple[list[str], np.ndarray]:
    """Load saved .npz centroid embeddings and ensure each vector is unit-length."""
    if not npz_path.exists():
        raise FileNotFoundError(f"Embeddings file not found: {npz_path}")

    names: list[str] = []
    vectors: list[np.ndarray] = []

    with np.load(npz_path) as data:
        for name in data.files:
            mat = np.atleast_2d(np.asarray(data[name], dtype=np.float32))
            norms = np.linalg.norm(mat, axis=1, keepdims=True)
            valid = norms[:, 0] > 0.0
            if not np.any(valid):
                continue

            # Guarantees a single unit-normalized centroid even if a multi-row array is loaded
            centroid = np.mean(mat[valid] / norms[valid], axis=0)
            c_norm = float(np.linalg.norm(centroid))
            if c_norm > 0.0:
                names.append(name)
                vectors.append(centroid / c_norm)

    if not names:
        raise ValueError(f"No valid embeddings found in {npz_path}")

    return names, np.vstack(vectors)


def identify_personalities(
    faces: list[dict],
    ref_names: list[str],
    ref_matrix: np.ndarray,
    threshold: float,
    min_face_size: int = 32,
) -> list[dict]:
    """Match detected faces against unit-normalized reference centroids."""
    valid_faces = [
        f for f in faces
        if (f["bbox"][2] - f["bbox"][0]) >= min_face_size
        and (f["bbox"][3] - f["bbox"][1]) >= min_face_size
    ]
    if not valid_faces:
        return []

    cand_matrix = np.vstack([f["embedding"] for f in valid_faces]).astype(np.float32)  # (N_faces, 512)
    norms = np.linalg.norm(cand_matrix, axis=1, keepdims=True)
    cand_matrix = np.divide(cand_matrix, norms, out=np.zeros_like(cand_matrix), where=norms > 0)

    sim_matrix = cand_matrix @ ref_matrix.T  # Cosine similarity: (N_faces, N_identities)

    best_by_person: dict[str, dict] = {}
    for face_idx, face in enumerate(valid_faces):
        person_idx = int(np.argmax(sim_matrix[face_idx]))
        score = float(sim_matrix[face_idx, person_idx])

        if score >= threshold:
            person_name = ref_names[person_idx]
            if (
                person_name not in best_by_person
                or score > best_by_person[person_name]["similarity"]
            ):
                best_by_person[person_name] = {
                    "name": person_name,
                    "similarity": round(score, 4),
                    "bbox": face["bbox"],
                }

    return sorted(best_by_person.values(), key=lambda item: item["similarity"], reverse=True)


def save_results(results: list[dict], output_path: Path) -> None:
    output_path.parent.mkdir(parents=True, exist_ok=True)
    if output_path.suffix.lower() == ".csv":
        with output_path.open("w", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerow(["image", "faces_detected", "recognized_personalities", "scores"])
            for row in results:
                names = ";".join(p["name"] for p in row["personalities"])
                scores = ";".join(f"{p['similarity']:.4f}" for p in row["personalities"])
                writer.writerow([row["image"], row["faces_detected"], names, scores])
    else:
        with output_path.open("w", encoding="utf-8") as f:
            json.dump(results, f, indent=2, ensure_ascii=False)


def main():
    parser = argparse.ArgumentParser(
        description="Label images in a folder with recognized personalities using stored embeddings."
    )
    parser.add_argument("--input_folder", type=str, required=True,
                        help="path to the folder containing images to label")
    parser.add_argument("--embeddings_file", type=str, required=True,
                        help="path to the .npz file generated by the embedding script")
    parser.add_argument("--output_file", type=str, default=None,
                        help="optional path to save labels (.json or .csv)")
    parser.add_argument("--threshold", type=float, default=0.45,
                        help="cosine similarity threshold for recognition (default: 0.45)")
    parser.add_argument("--min_face_size", type=int, default=32,
                        help="minimum face width/height in pixels to evaluate (default: 32)")
    parser.add_argument("--backend", type=str, choices=["auraface", "insightface"], default="auraface",
                        help="recognition backend (default: 'auraface' [Apache-2.0/MIT]; "
                             "'insightface' downloads non-commercial research weights)")
    parser.add_argument("--model_name", type=str, default="buffalo_l",
                        help="InsightFace model pack name when --backend insightface is used")
    parser.add_argument("--det_thresh", type=float, default=0.4,
                        help="detection threshold for face detection")
    parser.add_argument("--det_size", type=int, nargs=2, default=(640, 640),
                        help="detection size for face detection")
    parser.add_argument("--ctx_id", type=int, default=-1,
                        help="context id for the model (-1 for CPU, >=0 for GPU)")
    parser.add_argument("--cache_dir", type=Path, default=Path.home() / ".cache" / "face-embeddings",
                        help="directory to cache downloaded ONNX weights")
    parser.add_argument("--only_matches", action="store_true",
                        help="only print images where at least one personality was recognized")

    args = parser.parse_args()
    det_size = tuple(args.det_size)

    ref_names, ref_matrix = load_reference_embeddings(Path(args.embeddings_file))
    print(f"Loaded {len(ref_names)} reference identities from {args.embeddings_file}", file=sys.stderr)

    if args.backend == "auraface":
        from src.helpers.aura_face_extractor import AuraFaceExtractor
        extractor = AuraFaceExtractor(
            cache_dir=args.cache_dir,
            det_thresh=args.det_thresh,
            det_size=det_size,
            ctx_id=args.ctx_id,
        )
    else:
        from src.helpers.insight_face_extractor import InsightFaceExtractor
        extractor = InsightFaceExtractor(
            model_name=args.model_name,
            det_thresh=args.det_thresh,
            det_size=det_size,
            ctx_id=args.ctx_id,
        )

    input_dir = Path(args.input_folder)
    image_paths = sorted(
        p for p in input_dir.rglob("*")
        if p.is_file() and p.suffix.lower() in IMAGE_EXTENSIONS
    )

    if not image_paths:
        print(f"No images found in {input_dir}", file=sys.stderr)
        return

    all_results: list[dict] = []

    for image_path in image_paths:
        img = cv2.imread(str(image_path))
        rel_name = str(image_path.relative_to(input_dir))

        if img is None:
            print(f"[warn] Could not read image: {rel_name}", file=sys.stderr)
            continue

        faces = extractor.get_all_embeddings(img)
        recognized = identify_personalities(
            faces,
            ref_names,
            ref_matrix,
            threshold=args.threshold,
            min_face_size=args.min_face_size,
        )

        all_results.append(
            {
                "image": rel_name,
                "faces_detected": len(faces),
                "personalities": recognized,
            }
        )

        if recognized:
            labels_str = ", ".join(f"{p['name']} ({p['similarity']:.2f})" for p in recognized)
            print(f"{rel_name}: {labels_str}")
        elif not args.only_matches:
            print(f"{rel_name}: [none] (faces detected: {len(faces)})")

    if args.output_file:
        out_path = Path(args.output_file)
        save_results(all_results, out_path)
        print(f"\nSaved labels for {len(all_results)} images to {out_path}", file=sys.stderr)


if __name__ == "__main__":
    main()